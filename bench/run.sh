#!/bin/sh
# Run the reviewer benchmark for one model.
#
#   bench/run.sh <model> [code|design|all] [repeats]
#   bench/run.sh mistral-large-3:675b-cloud all 3
#
# Generates config/agents/bench-candidate.yaml from bench/agent-template.yaml,
# runs the bench config(s) review-only, scores each run against the manifest,
# and appends to bench/results.csv. The generated agent file is removed on
# exit. Methodology: bench/README.md.
set -eu

MODEL=${1:?usage: bench/run.sh <model> [code|design|all] [repeats]}
TASKS=${2:-all}
REPEATS=${3:-1}

cd "$(dirname "$0")/.."
CANDIDATE=config/agents/bench-candidate.yaml

# Refuse to clobber a real agent file; only ever manage our own generated one.
if [ -e "$CANDIDATE" ] && ! grep -q 'generated by bench/run.sh' "$CANDIDATE"; then
    echo "bench: $CANDIDATE exists and was not generated by this script; refusing" >&2
    exit 2
fi
trap 'rm -f "$CANDIDATE"' EXIT

# A baseline (claude, codex) is an EXISTING agent measured through its own
# yaml -- the ollama template would wrap it in the wrong harness. A claude-*
# model id is an Anthropic variant: claude.yaml with only the model swapped
# (effort stays at the production setting, so the model is the one variable).
# Everything else is an ollama model generated from the template.
if [ -f "config/agents/$MODEL.yaml" ]; then
    {
        echo "# generated by bench/run.sh -- do not edit, do not commit"
        cat "config/agents/$MODEL.yaml"
    } >"$CANDIDATE"
elif [ "${MODEL#claude-}" != "$MODEL" ]; then
    {
        echo "# generated by bench/run.sh -- do not edit, do not commit"
        sed "s|^model: .*|model: $MODEL|" config/agents/claude.yaml
    } >"$CANDIDATE"
else
    {
        echo "# generated by bench/run.sh -- do not edit, do not commit"
        sed "s|__MODEL__|$MODEL|" bench/agent-template.yaml
    } >"$CANDIDATE"
    # Record the exact model the tag resolves to right now: floating :cloud
    # tags can be re-pointed between runs, and a measurement of an unknown
    # model is not a measurement (see config/agents/deepseek-ollama.yaml).
    ollama show "$MODEL" 2>/dev/null | sed -n '1,8p' || echo "bench: WARNING: ollama show $MODEL failed" >&2
fi

make build >/dev/null

run_task() {
    task=$1 rep=$2
    case $task in
    code)   cfg=bench-code   target=bench/testdata/target-code   manifest=bench/manifest-code.yaml ;;
    design) cfg=bench-design target=bench/testdata/target-design manifest=bench/manifest-design.yaml ;;
    esac
    echo "bench: $MODEL / $task / repeat $rep"
    ./fixpoint "$cfg" -target "$target" --trusted-target --trusted-bundle || {
        # exit 4 is review-only's normal termination; anything else is the
        # candidate failing, which the bench records rather than hides.
        code=$?
        if [ "$code" != 4 ]; then
            echo "bench: run exited $code (recorded; a model that cannot finish a run cannot hold a seat)" >&2
        fi
    }
    summary=$(ls -t .fixpoint/*/summary-*.json 2>/dev/null | head -1)
    if [ -z "$summary" ]; then
        echo "bench: no summary produced; nothing to score" >&2
        return 1
    fi
    python3 bench/score.py "$manifest" "$summary" "$MODEL" "$rep"
}

rep=1
while [ "$rep" -le "$REPEATS" ]; do
    case $TASKS in
    code | design) run_task "$TASKS" "$rep" ;;
    all)
        run_task code "$rep"
        run_task design "$rep"
        ;;
    *)
        echo "bench: unknown task set '$TASKS' (want code|design|all)" >&2
        exit 2
        ;;
    esac
    rep=$((rep + 1))
done

echo "bench: done -> bench/results.csv"
