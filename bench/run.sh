#!/bin/sh
# Run the reviewer benchmark for one model.
#
#   bench/run.sh <model> [go|design|all|<lang>,...] [repeats]
#   bench/run.sh mistral-large-3:675b-cloud all 3
#
# Generates config/agents/bench-candidate.yaml from bench/agent-template.yaml,
# runs the bench config(s) review-only, scores each run against the manifest,
# and appends to bench/results.csv. The generated agent file is removed on
# exit. Methodology: bench/README.md.
#
# Each lens runs inside bench/sandbox.sh (config/bench-code.yaml's
# sandbox.command): it cannot read this checkout or ~/.fixpoint, and it can write
# nothing but its CLI's own state and scratch. That is why this script puts bench/
# on PATH and rewrites a codex candidate's own sandbox off, below.
set -eu

MODEL=${1:?usage: bench/run.sh <model> [go|design|all|<lang>,...] [repeats]}
TASKS=${2:-all}
REPEATS=${3:-1}

cd "$(dirname "$0")/.."
CANDIDATE=config/agents/bench-candidate.yaml

# config/bench-code.yaml and config/bench-design.yaml confine every lens with
# `sandbox.command: [sandbox.sh, ...]`, a BARE name: a relative path would resolve
# against the lens's target (the staged copy), which does not hold bench/.
# fixpoint looks the name up on PATH, so this directory goes on it; sandbox.sh
# takes the entry back off before it execs the agent.
PATH=$(pwd -P)/bench:$PATH
export PATH
LOCK=bench/.run.lock

# The bench is inherently SERIAL: one generated candidate agent file, one
# results.csv appended to, and one .fixpoint/ to find this run's summary in.
# Two overlapping invocations would clobber each other's model and could
# attribute one run's measurements to the other's model (review run
# 20260813-161029) -- fabricated rows in the file that decides panel seats. So
# concurrency is refused rather than accommodated.
#
# noclobber, not mkdir: Ubuntu 26.04 ships uutils coreutils, whose mkdir is not
# a reliable atomic test-and-set, while `set -C` redirection is POSIX and fails
# if the file exists.
if ! (set -C; echo "$$" >"$LOCK") 2>/dev/null; then
    echo "bench: another benchmark is running (lock $LOCK held by PID $(cat "$LOCK" 2>/dev/null)); the bench is serial by design -- wait for it, or remove the lock if that PID is gone" >&2
    exit 2
fi
trap 'rm -f "$LOCK" "$CANDIDATE"' EXIT

# Refuse to clobber a real agent file; only ever manage our own generated one.
if [ -e "$CANDIDATE" ] && ! grep -q 'generated by bench/run.sh' "$CANDIDATE"; then
    echo "bench: $CANDIDATE exists and was not generated by this script; refusing" >&2
    exit 2
fi

# A shipped agent (claude-opus, claude-sonnet, codex, ...) is an EXISTING agent
# measured through its own yaml -- the ollama template would wrap it in the
# wrong harness. A claude-*
# model id is an Anthropic variant: claude-opus.yaml with only the model swapped
# (effort stays at the production setting, so the model is the one variable).
# vllm@<hf-repo> is a model we serve ourselves, codex@<id> and any other id
# with a slash are OpenRouter, ollama-codex@<tag> is an ollama model through the
# codex harness, ollama-direct@<tag> is the same harness straight to ollama.com,
# and everything else is an ollama model.
if [ -f "config/agents/$MODEL.yaml" ]; then
    {
        echo "# generated by bench/run.sh -- do not edit, do not commit"
        cat "config/agents/$MODEL.yaml"
    } >"$CANDIDATE"
elif [ "${MODEL#claude-}" != "$MODEL" ]; then
    {
        echo "# generated by bench/run.sh -- do not edit, do not commit"
        sed "s|^model: .*|model: $MODEL|" config/agents/claude-opus.yaml
    } >"$CANDIDATE"
elif [ "${MODEL#vllm@}" != "$MODEL" ]; then
    # vllm@<hf-repo> is a model WE serve, on a rented GPU running
    # bench/vllm-serve.sh: the claude harness pointed at that server's
    # /v1/messages. Checked before the slash rule below, which would otherwise
    # send the request -- and the key -- to OpenRouter.
    #
    # The key is ALWAYS overwritten, never defaulted, for the OpenRouter
    # route's reason: an exported ANTHROPIC_AUTH_TOKEN would otherwise be sent
    # to a machine on someone else's network.
    if [ -z "${VLLM_BASE_URL:-}" ] || [ -z "${VLLM_API_KEY:-}" ]; then
        echo "bench: $MODEL is a self-served model; set VLLM_BASE_URL (e.g. http://localhost:8000 over an SSH tunnel, see bench/vllm-serve.sh) and VLLM_API_KEY" >&2
        exit 2
    fi
    ANTHROPIC_AUTH_TOKEN=$VLLM_API_KEY
    export ANTHROPIC_AUTH_TOKEN
    unset ANTHROPIC_API_KEY
    # Fail before the sweep, not one lens in: a server that is down, still
    # loading, or serving a different model would otherwise be recorded as the
    # candidate failing every session.
    served=$(curl -fsS -H "Authorization: Bearer $VLLM_API_KEY" "${VLLM_BASE_URL%/}/v1/models") || {
        echo "bench: cannot reach ${VLLM_BASE_URL%/}/v1/models -- is the server up?" >&2
        exit 2
    }
    # An exact match on data[].id, not a substring of the body: vLLM also
    # lists the path the weights were loaded from as `root`, so a server
    # running these weights under another --served-model-name still carries
    # the repo id, and would pass -- then 404 every session.
    if ! printf '%s' "$served" | python3 -c '
import json, sys
ids = [m.get("id") for m in json.load(sys.stdin).get("data", [])]
sys.exit(0 if sys.argv[1] in ids else 1)' "${MODEL#vllm@}" 2>/dev/null; then
        echo "bench: ${VLLM_BASE_URL%/} does not serve ${MODEL#vllm@}: $served" >&2
        exit 2
    fi
    # Record what is being measured: the server's model list carries the
    # context length it was started with, which a run log should keep.
    echo "bench: serving: $served"
    {
        echo "# generated by bench/run.sh -- do not edit, do not commit"
        sed -e "s|__MODEL__|${MODEL#vllm@}|g" -e "s|__BASE_URL__|${VLLM_BASE_URL%/}|g" \
            bench/agent-template-vllm.yaml
    } >"$CANDIDATE"
elif [ "${MODEL#ollama-codex@}" != "$MODEL" ] || [ "${MODEL#ollama-direct@}" != "$MODEL" ]; then
    # ollama-codex@<tag> is an ollama model driven by the CODEX harness
    # (`ollama launch codex`) instead of the claude one: same model, same
    # payer, the harness is the variable. Effort is live on this route, unlike
    # the claude one -- see bench/agent-template-ollama-codex.yaml.
    #
    # ollama-direct@<tag> is the same harness talking to ollama.com itself, with
    # no local server: the transport is the variable. See
    # bench/agent-template-ollama-direct.yaml.
    #
    # Both take a #<effort> suffix, as codex@ does, and for its reason: the
    # suffix stays in the recorded model id. `max` is valid here, unlike on
    # OpenRouter -- it is the deepest level some ollama models list.
    case $MODEL in
    ollama-direct@*)
        spec=${MODEL#ollama-direct@}
        template=bench/agent-template-ollama-direct.yaml
        # Fail before the sweep, not one lens in: without the key every session
        # is a 401, recorded as the candidate failing.
        if [ -z "${OLLAMA_API_KEY:-}" ]; then
            echo "bench: $MODEL talks to ollama.com directly; set OLLAMA_API_KEY" >&2
            exit 2
        fi
        ;;
    *)
        spec=${MODEL#ollama-codex@}
        template=bench/agent-template-ollama-codex.yaml
        ;;
    esac
    effort=xhigh
    case $spec in
    *"#"*)
        effort=${spec#*"#"}
        spec=${spec%%"#"*}
        ;;
    esac
    case $effort in
    low | medium | high | xhigh | max) ;;
    *)
        echo "bench: $MODEL: effort '$effort' is not one of low, medium, high, xhigh, max" >&2
        exit 2
        ;;
    esac
    {
        echo "# generated by bench/run.sh -- do not edit, do not commit"
        sed -e "s|__MODEL__|$spec|" \
            -e "s|^effort: xhigh.*|effort: $effort # set by bench/run.sh from the #<effort> suffix|" \
            "$template"
    } >"$CANDIDATE"
    ollama show "$spec" 2>/dev/null | sed -n '1,8p' || echo "bench: WARNING: ollama show $spec failed" >&2
elif [ "${MODEL#codex@}" != "$MODEL" ]; then
    # codex@<openrouter-id> routes through the CODEX harness instead of the
    # claude one. It exists because the claude harness cannot read some models'
    # replies on this route at all: OpenRouter's Anthropic translation puts a
    # signature-only thinking block AFTER the text for e.g. gemini-3.7-flash,
    # and the harness's result field comes out empty on every call (measured
    # 2026-08-19; grok works there only because its text arrives last). The
    # codex responses-API wire format has no block-order dependence.
    #
    # Same card-billing rules as the claude route below; comparability is
    # against the CODEX baseline, which shares this harness.
    if [ -z "${OPENROUTER_API_KEY:-}" ]; then
        echo "bench: $MODEL is an OpenRouter id but OPENROUTER_API_KEY is not set" >&2
        exit 2
    fi
    # codex@<id>#<effort> pins the reasoning effort for this sweep (the template
    # default is high, matched to the codex baseline). The suffix stays in the
    # model id that results.csv records, so a deeper-effort sweep is its own row
    # and never overwrites or is mistaken for the high one.
    spec=${MODEL#codex@}
    effort=high
    case $spec in
    *"#"*)
        effort=${spec#*"#"}
        spec=${spec%%"#"*}
        ;;
    esac
    case $effort in
    low | medium | high | xhigh) ;;
    *)
        echo "bench: $MODEL: effort '$effort' is not one of low, medium, high, xhigh" >&2
        exit 2
        ;;
    esac
    {
        echo "# generated by bench/run.sh -- do not edit, do not commit"
        sed -e "s|__MODEL__|$spec|" \
            -e "s|^effort: high.*|effort: $effort # set by bench/run.sh from the codex@<id>#<effort> suffix|" \
            bench/agent-template-openrouter-codex.yaml
    } >"$CANDIDATE"
elif [ "${MODEL#*/}" != "$MODEL" ]; then
    # A slash means an OpenRouter id (x-ai/grok-4.6, moonshotai/...). This
    # route bills a card, and the agent yaml points ANTHROPIC_BASE_URL at
    # openrouter.ai while passing ANTHROPIC_AUTH_TOKEN through -- so the token
    # is ALWAYS overwritten with the OpenRouter key, never merely defaulted.
    # An operator with ANTHROPIC_AUTH_TOKEN already exported (the normal setup
    # for Claude Code against a gateway) would otherwise have sent their
    # Anthropic credential to a third party (review run 20260813-124710).
    if [ -z "${OPENROUTER_API_KEY:-}" ]; then
        echo "bench: $MODEL is an OpenRouter id but OPENROUTER_API_KEY is not set" >&2
        exit 2
    fi
    ANTHROPIC_AUTH_TOKEN=$OPENROUTER_API_KEY
    export ANTHROPIC_AUTH_TOKEN
    # ANTHROPIC_API_KEY takes precedence over the auth token inside the
    # harness, so an exported one would silently bill Anthropic for a model
    # bought elsewhere -- and reach openrouter.ai on the way.
    unset ANTHROPIC_API_KEY
    {
        echo "# generated by bench/run.sh -- do not edit, do not commit"
        sed "s|__MODEL__|$MODEL|" bench/agent-template-openrouter.yaml
    } >"$CANDIDATE"
else
    {
        echo "# generated by bench/run.sh -- do not edit, do not commit"
        sed "s|__MODEL__|$MODEL|" bench/agent-template.yaml
    } >"$CANDIDATE"
    # Record the exact model the tag resolves to right now: floating :cloud
    # tags can be re-pointed between runs, and a measurement of an unknown
    # model is not a measurement (see config/agents/deepseek-ollama.yaml).
    ollama show "$MODEL" 2>/dev/null | sed -n '1,8p' || echo "bench: WARNING: ollama show $MODEL failed" >&2
fi

# bench/sandbox.sh confines every lens (read: not the checkout, not ~/.fixpoint;
# write: not the target, not $HOME), and sandboxes do not nest. The `--sandbox
# read-only` a codex-harness agent carries is seatbelt (macOS) or bubblewrap
# (Linux) around each of its shell commands; inside the wrapper that cannot start,
# and every command a lens ran failed with `sandbox_apply: Operation not
# permitted` (measured 2026-11-24). So the GENERATED candidate turns codex's own
# sandbox off and the wrapper is what enforces read-only, for the bench only:
# config/agents/*.yaml keep their `--sandbox read-only`. A claude-harness
# candidate has no such line and is left as it is.
if grep -q '^  - --sandbox read-only' "$CANDIDATE"; then
    sed 's|^\(  - \)--sandbox read-only.*|\1--sandbox danger-full-access # bench/run.sh: the wrapper, bench/sandbox.sh, enforces read-only now; codex'"'"'s own sandbox cannot nest inside it|' \
        "$CANDIDATE" >"$CANDIDATE.tmp" && mv "$CANDIDATE.tmp" "$CANDIDATE"
    grep -q '^  - --sandbox danger-full-access' "$CANDIDATE" || {
        echo "bench: could not switch the codex sandbox off in $CANDIDATE" >&2
        exit 2
    }
fi

make build >/dev/null

run_task() {
    task=$1 rep=$2
    # One line per target. Every code-flavoured language shares bench-code.yaml
    # -- the config names the lenses, and -target below points them at a
    # different tree -- so adding a language is an entry here plus a manifest,
    # not a new config. `code` stays as an alias for `go`, which is what every
    # invocation and every row in results.csv meant before the rename.
    case $task in
    go | code) cfg=bench-code   manifest=bench/manifest-go.yaml     target=bench/testdata/target-go ;;
    design)    cfg=bench-design manifest=bench/manifest-design.yaml target=bench/testdata/target-design ;;
    *)
        # A language target added to bench/testdata/target-<name> with a
        # matching bench/manifest-<name>.yaml is runnable with no edit here.
        cfg=bench-code
        manifest=bench/manifest-$task.yaml
        target=bench/testdata/target-$task
        if [ ! -f "$manifest" ] || [ ! -d "$target" ]; then
            echo "bench: unknown task '$task' (no $manifest / $target)" >&2
            return 1
        fi
        ;;
    esac
    echo "bench: $MODEL / $task / repeat $rep"
    # Remember what existed BEFORE this invocation: the summary to score is the
    # one this run created, never merely the newest on disk. Scoring the newest
    # (the first version of this script) silently attributed a previous run's
    # results to the current model whenever startup failed before a summary was
    # written -- fabricated numbers, in the file that decides panel seats
    # (review run 20260813-124710).
    marker=$(mktemp)
    # THE LENS REVIEWS A COPY OUTSIDE THE REPOSITORY, never bench/testdata itself.
    # A lens's cwd is its target, and the read-only sandbox confines writes, not
    # reads: from bench/testdata/target-<x>, `../../manifest-<x>.yaml` is the
    # answer key, and `.fixpoint/` holds every earlier model's findings. hy4 read
    # both and scored go 53/56 (2026-11-23); two glm-5.3-flash rows of 2026-10-28
    # had read their manifests too. A fresh directory per run has nothing above
    # the target and does not name the repository in its path. bench/sandbox.sh,
    # which every lens runs inside, then makes the checkout unreadable rather than
    # merely absent from the path; score.py's key_reads() refuses a row whose
    # lens reached the key anyway.
    # `pwd -P`: macOS mktemp answers under /var, a symlink to /private/var, and
    # fixpoint refuses a -target with a symlink in any component.
    #
    # EVERY STEP IS CHECKED BY HAND: run_task is called under `||`, where
    # `set -e` is off. An unchecked `work=$(mktemp -d)` that failed left work
    # empty, `cd ""` stays put under dash, and the cleanup below would then have
    # been `rm -rf` of the checkout itself (review run 20261124-104533). $work is
    # only ever what mktemp returned; $stage, the resolved path, is never removed.
    work=$(mktemp -d) || work=
    if [ -z "$work" ] || [ ! -d "$work" ]; then
        echo "bench: mktemp -d failed; nothing to score" >&2
        rm -f "$marker"
        return 1
    fi
    stage=$(cd "$work" && pwd -P) || stage=
    root=$(pwd -P)
    # A TMPDIR inside the checkout would put the copy back under the key.
    case "$stage/" in
    / | "$root"/*)
        echo "bench: the scratch directory '$stage' is empty or inside the checkout ($root); set TMPDIR elsewhere" >&2
        rm -rf "$work"
        rm -f "$marker"
        return 1
        ;;
    esac
    # Only what git would show a reviewer, as fixpoint's own collector did when
    # the target sat in the worktree: tracked and untracked-but-not-ignored.
    # A plain `cp -R` also carried ignored build output (the 10 MB `linkd` that
    # `make bench-check` leaves in target-go, target-csharp/obj), so what a
    # model was shown depended on which host had built what.
    if ! mkdir "$stage/repo" ||
        ! (cd "$target" && git ls-files -z --cached --others --exclude-standard . | tar -cf - --null -T -) |
        tar -xf - -C "$stage/repo" ||
        [ -z "$(ls -A "$stage/repo")" ]; then
        echo "bench: could not stage $target in $stage/repo; nothing to score" >&2
        rm -rf "$work"
        rm -f "$marker"
        return 1
    fi
    ./fixpoint "$cfg" -target "$stage/repo" --trusted-target --trusted-bundle || {
        # exit 4 is review-only's normal termination; anything else is the
        # candidate failing, which the bench records rather than hides.
        code=$?
        if [ "$code" != 4 ]; then
            echo "bench: run exited $code (recorded; a model that cannot finish a run cannot hold a seat)" >&2
        fi
    }
    rm -rf "$work"
    # With concurrency refused above, a run directory newer than the marker can
    # only be this invocation's.
    rundir=$(ls -dt .fixpoint/*/ 2>/dev/null | while read -r d; do
        [ "$d" -nt "$marker" ] && echo "$d"
    done | head -1)
    rm -f "$marker"
    if [ -z "$rundir" ]; then
        echo "bench: this invocation created no run directory; nothing to score" >&2
        return 1
    fi
    summary=$(ls -t "$rundir"summary-*.json 2>/dev/null | head -1)
    if [ -z "$summary" ]; then
        echo "bench: $rundir has no summary (the run died before writing one); nothing to score" >&2
        return 1
    fi
    python3 bench/score.py "$manifest" "$summary" "$MODEL" "$rep"
}

# REPEAT_START lets a re-run be labelled repeat 2 rather than colliding with the
# repeat-1 row it is correcting. A target re-run after a contract failure must
# NOT overwrite the failed row -- that row is the record of the failure, which
# is the benchmark's disqualifier and the most important thing it measured.
rep=${REPEAT_START:-1}
last=$((rep + REPEATS - 1))
while [ "$rep" -le "$last" ]; do
    case $TASKS in
    all)
        # `all` is deliberately the CALIBRATED pair, not every target on disk:
        # it is what every published score out of 100 means, and silently
        # widening it as languages are added would change what a comparable
        # run costs and what its total is. Name a language to measure it.
        # Guarded like the list below, and for its reason: go failing to score
        # must not leave design unmeasured.
        run_task go "$rep" || echo "bench: go did not score; continuing" >&2
        run_task design "$rep" || echo "bench: design did not score; continuing" >&2
        ;;
    *)
        # Comma- or space-separated list, so one invocation can sweep several
        # targets: TASK=go,rust,design
        # `|| true`, because `set -e` would otherwise abort the whole sweep on the
        # first target that fails to score. A calibration pass is 11 runs over ~2
        # hours; losing the remaining ten to one bad summary is not a tradeoff
        # worth making, and the failure is recorded either way.
        for one in $(echo "$TASKS" | tr ',' ' '); do
            run_task "$one" "$rep" || echo "bench: $one did not score; continuing" >&2
        done
        ;;
    esac
    rep=$((rep + 1))
done

echo "bench: done -> bench/results.csv"
